def _slug_id(value: str, fallback: str = "pipeline") -> str:
    slug = re.sub(r"[^A-Za-z0-9_-]+", "_", value.strip()).strip("_")
    if not slug:
        slug = fallback
    if not re.match(r"^[A-Za-z]", slug):
        slug = f"{fallback}_{slug}"
    return slug[:128]


def _human_name(description_text: str, source_path: Path) -> str:
    first_line = next((line.strip() for line in description_text.splitlines() if line.strip()), "")
    if first_line:
        return first_line[:80]
    return source_path.stem.replace("_", " ").replace("-", " ").title() or "Draft Pipeline"


def _format_from_path(path: str) -> str:
    suffix = Path(path).suffix.lower().lstrip(".")
    if suffix in {"jsonl", "ndjson"}:
        return "json"
    return suffix or "text"


